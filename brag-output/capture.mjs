import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const output = path.dirname(fileURLToPath(import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
async function open(route) {
  await page.goto('http://127.0.0.1:5174' + route, { waitUntil: 'networkidle' });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(850);
}
await open('/');
const image = await page.locator('.portrait-frame img').evaluate(img => ({ loaded: img.complete && img.naturalWidth > 0, src: img.getAttribute('src') }));
if (!image.loaded) throw new Error('Preserved hero image did not load');
await page.screenshot({ path: path.join(output, '01-hero.png') });
await page.getByRole('button', { name: 'Pause motion', exact: true }).click();
if (await page.locator('.landing').getAttribute('data-motion') !== 'paused') throw new Error('Motion pause failed');
await page.getByRole('button', { name: 'Play motion', exact: true }).click();
await open('/app');
await page.getByPlaceholder('Ask Mio anything…').fill('Find headphones under $200');
await page.getByRole('button', { name: 'Send message', exact: true }).click();
await page.locator('.experience-pick').first().waitFor();
await page.screenshot({ path: path.join(output, '02-conversation.png') });
await open('/providers');
await page.locator('#directory').evaluate(el => window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY - 110, behavior: 'instant' }));
await page.screenshot({ path: path.join(output, '03-integrations.png') });
const providerCount = await page.locator('.integration-card').count();
await open('/');
await page.locator('#in-action').evaluate(el => window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY - 90, behavior: 'instant' }));
await page.waitForTimeout(750);
await page.getByRole('tab', { name: 'Travel', exact: true }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: path.join(output, '04-product.png') });
await page.setViewportSize({ width: 390, height: 844 });
await open('/');
await page.screenshot({ path: path.join(output, 'mobile-hero.png'), fullPage: false });
const mobileOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
await page.emulateMedia({ reducedMotion: 'reduce' });
await open('/');
const reduced = await page.locator('.float-request').evaluate(el => getComputedStyle(el).animationName);
await writeFile(path.join(output, 'verification.json'), JSON.stringify({ image, providerCount, mobileOverflow, reducedMotionAnimation: reduced, errors }, null, 2));
await browser.close();
console.log(JSON.stringify({ image, providerCount, mobileOverflow, reducedMotionAnimation: reduced, errors }));
